import os
from google import genai

client = genai.Client(api_key=os.environ["GEMINI_API_KEY"])


def analyze_news(title, link):

    prompt = f"""
أنت محلل اقتصادي محترف تكتب لقناة تيليجرام عربية متخصصة في الأسواق المالية.

التعليمات:

- اعتمد فقط على المعلومات الموجودة في الخبر.
- لا تخترع أي معلومة.
- إذا لم يذكر الخبر تأثير أصل مالي معين فاكتب "التأثير محدود حالياً".
- اجعل الأسلوب احترافياً وسهل القراءة.
- لا تستخدم Markdown نهائياً.
- لا تستخدم ** أو __ أو # أو [] أو ().
- استخدم الإيموجي فقط.
- لا تتجاوز 180 كلمة.

اكتب بالشكل التالي:

🚨 عنوان جذاب للخبر

📰 ملخص الخبر:
اكتب ملخصاً من سطرين أو ثلاثة.

📊 التأثير المتوقع:
🥇 الذهب:
💵 الدولار:
📈 الأسهم:
🪙 العملات الرقمية:
🛢 النفط:

⭐ أهمية الخبر:
اكتبها بهذا الشكل:
7/10

💡 ماذا يعني ذلك للمستثمر؟
اكتب جملة واحدة فقط.

عنوان الخبر:
{title}

رابط الخبر:
{link}
"""

    response = client.models.generate_content(
        model="gemini-3.6-flash",
        contents=prompt,
    )

    return response.text
